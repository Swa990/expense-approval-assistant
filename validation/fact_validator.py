def to_dict(value: Any) -> dict:
    if hasattr(value, "model_dump"):
        return value.model_dump(mode="json")
    if isinstance(value, dict):
        return value
    raise TypeError("Expected a dictionary or Pydantic model.")


def normalize_value(value: Any):
    if value is None:
        return None
    return str(value).strip().lower()


def get_document_facts(unstructured_facts: list) -> list:
    documents = []

    for document in unstructured_facts or []:
        for page in document.get("extracted_pages", []):
            documents.append({
                "filename": document.get("filename"),
                "page_number": page.get("page_number"),
                "facts": page.get("facts", {})
            })

    return documents


def parse_decimal(value: Any):
    if value is None or isinstance(value, bool):
        return None

    try:
        return Decimal(str(value).replace(",", "").strip())
    except (InvalidOperation, ValueError, TypeError):
        return None


def add_finding(findings, field, submitted_value, document_value, filename, reason):
    findings.append({
        "field": field,
        "submitted_value": submitted_value,
        "document_value": document_value,
        "source": filename,
        "status": "MISMATCH",
        "reason": reason
    })


def compare_facts(structured_facts: dict, unstructured_facts: list) -> list:
    """
    Independent factual verification.
    This function does not decide policy compliance.
    """

    findings = []
    documents = get_document_facts(unstructured_facts)

    amount_fields = (
        "total_amount",
        "invoice_amount",
        "bill_amount",
        "amount_due"
    )

    comparable_fields = {
        "currency": ("currency",),
        "category": ("expense_category", "category"),
        "transaction_date": ("transaction_date", "expense_date", "date")
    }

    submitted_amount = parse_decimal(structured_facts.get("amount"))

    for document in documents:
        facts = document["facts"]
        filename = document["filename"]

        document_amount = next(
            (
                parse_decimal(facts.get(field))
                for field in amount_fields
                if parse_decimal(facts.get(field)) is not None
            ),
            None
        )

        if submitted_amount is not None and document_amount is not None:
            if abs(submitted_amount - document_amount) > Decimal("0.01"):
                add_finding(
                    findings,
                    "amount",
                    str(submitted_amount),
                    str(document_amount),
                    filename,
                    "Submitted amount differs from the extracted document amount."
                )

        for submitted_field, document_fields in comparable_fields.items():
            submitted_value = normalize_value(
                structured_facts.get(submitted_field)
            )

            document_value = next(
                (
                    normalize_value(facts.get(field))
                    for field in document_fields
                    if facts.get(field) is not None
                ),
                None
            )

            if submitted_value and document_value:
                if submitted_value != document_value:
                    add_finding(
                        findings,
                        submitted_field,
                        submitted_value,
                        document_value,
                        filename,
                        f"Submitted {submitted_field} differs from the document."
                    )

        confidence = normalize_value(facts.get("confidence"))

        if confidence in {"low", "very low"}:
            findings.append({
                "field": "document_extraction",
                "submitted_value": None,
                "document_value": confidence,
                "source": filename,
                "status": "UNKNOWN",
                "reason": "Extracted document information has low confidence."
            })

    return findings


def build_validation_input(
    structured_facts: dict,
    unstructured_facts: list,
    company_policies: list
) -> dict:

    employee_facts = to_dict(structured_facts)

    document_facts = get_document_facts(unstructured_facts)

    comparison_results = compare_facts(
        employee_facts,
        unstructured_facts
    )

    return {
        "employee_facts": employee_facts,
        "supporting_document_facts": document_facts,
        "deterministic_comparison_results": comparison_results,
        "company_policies": company_policies
    }



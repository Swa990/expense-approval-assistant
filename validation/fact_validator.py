def validate_response(result):
    if not isinstance(result, dict):
        raise ValueError("LLM response must be a JSON object.")

    required_fields = ["decision", "decision_reason", "missing_information"]

    missing_fields = [field for field in required_fields if field not in result]
    if missing_fields:
        raise ValueError(f"Missing decision fields: {missing_fields}")

    if result["decision"] not in {"APPROVE", "REJECT", "REQUIRES_REVIEW"}:
        raise ValueError("Invalid decision.")

    if not isinstance(result["decision_reason"], str):
        raise ValueError("decision_reason must be a string.")

    if not isinstance(result["missing_information"], list):
        raise ValueError("missing_information must be a list.")

    return result


def validate_with_llm(validation_input: dict, max_retries: int = 3) -> dict:
    last_error = None

    prompt = (
        VALIDATION_PROMPT
        + "\n\nVALIDATION INPUT:\n"
        + json.dumps(validation_input, indent=2, default=str)
    )

    for attempt in range(max_retries):
        try:
            response = _client.chat.completions.create(
                model=MODEL_NAME,
                temperature=0.1,
                max_tokens=2048,
                response_format={"type": "json_object"},
                messages=[
                    {
                        "role": "system",
                        # "content": (
                        #     "You are an enterprise expense validation assistant. "
                        #     "You MUST return a JSON object containing exactly these top-level keys: "
                        #     "validation_status, fact_findings, policy_findings, "
                        #     "missing_information, policy_violations, unknown_conditions, "
                        #     "requires_human_review, validation_summary. "
                        #     "Do not rename, omit, or nest these keys. "
                        #     "Return JSON only, without Markdown."
                        # )
                        "content": (
                            "You are an enterprise expense decision assistant. "
                            "Return exactly two JSON keys: decision and decision_reason. "
                            "Do not include any additional fields or explanations."
                        )
                        
                    },
                    {
                        "role": "user",
                        "content": prompt
                    }
                ]
            )

            # content = response.choices[0].message.content

            # if not content:
            #     raise ValueError("Empty validation response.")

            # result = json.loads(content)

            # return validate_response(result)
            content = response.choices[0].message.content

            if not content:
                raise ValueError("Empty validation response.")

            print("\nRAW QWEN RESPONSE:\n", content)

            result = json.loads(content)

            return validate_response(result)

        except Exception as error:
            last_error = error

            if attempt < max_retries - 1:
                time.sleep(5 * (attempt + 1))

    raise RuntimeError(
        f"Expense validation failed after {max_retries} attempts: {last_error}"
    ) from last_error


def validate_expense(
    structured_facts,
    unstructured_facts,
    company_policies
) -> dict:

    validation_input = build_validation_input(
        structured_facts,
        unstructured_facts,
        company_policies
    )

    validation_result = validate_with_llm(validation_input)

    validation_result["deterministic_comparison_results"] = (
        validation_input["deterministic_comparison_results"]
    )

    return validation_result
